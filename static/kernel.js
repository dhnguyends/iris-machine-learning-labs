function showNotice(message, isError) {
  const notice = document.getElementById("kernel-notice");
  notice.textContent = message || "";
  notice.classList.toggle("error-message", Boolean(isError));
}

function renderOutputs(container, outputs) {
  container.replaceChildren();
  if (!outputs.length) {
    const empty = document.createElement("span");
    empty.className = "output-placeholder";
    empty.textContent = "Cell completed with no output.";
    container.appendChild(empty);
    return;
  }

  outputs.forEach((output) => {
    if (output.type === "image") {
      const image = document.createElement("img");
      image.className = "kernel-image";
      image.alt = "Output generated by this Python cell";
      image.src = `data:image/png;base64,${output.data}`;
      container.appendChild(image);
      return;
    }

    const text = document.createElement("pre");
    text.className = output.type === "error" ? "kernel-error" : "kernel-text";
    text.textContent = output.text;
    container.appendChild(text);
  });
}

document.querySelectorAll(".run-cell").forEach((button) => {
  button.addEventListener("click", async () => {
    const cell = button.closest(".interactive-cell");
    const editor = cell.querySelector(".cell-editor");
    const output = cell.querySelector(".cell-output");
    button.disabled = true;
    button.textContent = "Running…";
    showNotice("", false);
    output.replaceChildren();

    try {
      const response = await fetch("/api/kernel/execute", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ code: editor.value }),
      });
      const result = await response.json();
      if (!response.ok) {
        showNotice(result.error || "The cell could not be run.", true);
      } else {
        renderOutputs(output, result.outputs);
        if (result.timed_out) {
          showNotice("The cell timed out; reset the kernel before continuing.", true);
        }
      }
    } catch (error) {
      showNotice(`Could not reach the Python kernel: ${error.message}`, true);
    } finally {
      button.disabled = false;
      button.innerHTML = 'Run cell <span aria-hidden="true">▶</span>';
    }
  });
});

document.getElementById("reset-kernel").addEventListener("click", async (event) => {
  const button = event.currentTarget;
  button.disabled = true;
  try {
    const response = await fetch("/api/kernel/reset", { method: "POST" });
    const result = await response.json();
    showNotice(result.message || result.error, !response.ok);
    if (response.ok) {
      document.querySelectorAll(".cell-output").forEach((output) => {
        output.replaceChildren();
        const placeholder = document.createElement("span");
        placeholder.className = "output-placeholder";
        placeholder.textContent = "Run this cell to see its output.";
        output.appendChild(placeholder);
      });
    }
  } catch (error) {
    showNotice(`Could not reset the Python kernel: ${error.message}`, true);
  } finally {
    button.disabled = false;
  }
});
